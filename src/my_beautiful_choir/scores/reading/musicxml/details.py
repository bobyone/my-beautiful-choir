# MusicXML chromatic is required in a transpose detail.
MUSICAL_DETAILS |= {"chromatic"}


def notation(element: Element[str], unsupported: set[str]) -> Notation | None:
    """Extract a known detail, reporting other musical content as unsupported."""
    kind = element.tag
    if kind in GRAPHICAL_ELEMENTS:
        return None
    if kind not in MUSICAL_DETAILS:
        unsupported.add(kind)
        return None
    children = []
    for child in element:
        if (detail := notation(child, unsupported)) is not None:
            children.append(detail)
    value = element.text or ""
    if kind not in {"words", "text", "elision"}:
        value = value.strip()
    if kind in _NUMERIC_DETAILS and value:
        value = _normalise_decimal(value)
    return Notation(kind, value, properties(element), tuple(children))


def properties(element: Element[str], *exclude: str) -> tuple[tuple[str, str], ...]:
    """Keep musical properties in a stable order."""
    return tuple(
        sorted(
            (key, value)
            for key, value in element.attrib.items()
            if key not in _GRAPHICAL_PROPERTIES and key not in exclude and key != "id"
        )
    )


def _normalise_decimal(value: str) -> str:
    if "." in value and all(char in "+-.0123456789" for char in value):
        signless = value.lstrip("+")
        stripped = signless.rstrip("0").rstrip(".")
        return stripped if stripped not in {"", "-"} else "0"
    return value
